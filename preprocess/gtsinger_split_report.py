"""Assign train / valid / test_seen / test_unseen splits to the GTSinger metadata and write a data report.

- test_unseen: every clip of the held-out singers
- a song is held out as a whole: for every singer who sings it and for all its groups
  (control, technique, paired speech); songs of the held-out singers are held-out songs too
- per remaining singer, whole songs are drawn (fixed seed) until valid and test_seen each
  reach --min_minutes of singing

Usage:
  python preprocess/gtsinger_split_report.py --meta_dir data/meta --unseen_singers IT-Bass-2 KO-Soprano-1
"""
import argparse
import collections
import json
import os
import random
import unicodedata

SPLITS = ['train', 'valid', 'test_seen', 'test_unseen']
TECHS = ['mix', 'falsetto', 'breathy', 'pharyngeal', 'vibrato', 'glissando']
REST = ('<AP>', '<SP>')


def song_key(it):
    lang, _, _, song = it['item_name'].split('#')[:4]
    return lang, unicodedata.normalize('NFC', song).casefold()


def assign_splits(sing, unseen, min_seconds, seed):
    """Returns {song_key: split} for held-out songs; everything else is train."""
    dur = collections.defaultdict(float)          # (singer, song) -> seconds of singing
    for it in sing:
        dur[(it['singer'], song_key(it))] += it['duration']
    singers_of = collections.defaultdict(set)
    for singer, song in dur:
        singers_of[song].add(singer)

    song_split = {song: 'test_seen' for (singer, song) in dur if singer in unseen}
    got = collections.defaultdict(float)          # (singer, split) -> seconds
    for (singer, song), d in dur.items():
        if song in song_split:
            got[(singer, song_split[song])] += d

    rng = random.Random(seed)
    for singer in sorted({s for s, _ in dur} - set(unseen)):
        for split in ('test_seen', 'valid'):
            cands = sorted(song for (s, song) in dur if s == singer and song not in song_split)
            rng.shuffle(cands)
            # prefer songs that do not overshoot the target much; singers with few, long songs take their shortest
            small = [c for c in cands if dur[(singer, c)] <= 2 * min_seconds]
            order = small + sorted((c for c in cands if c not in small), key=lambda c: dur[(singer, c)])
            for song in order:
                if got[(singer, split)] >= min_seconds:
                    break
                song_split[song] = split
                for other in singers_of[song]:
                    got[(other, split)] += dur[(other, song)]
    return song_split


def table(header, rows):
    out = ['| ' + ' | '.join(header) + ' |', '|' + '|'.join(['---'] + ['---:'] * (len(header) - 1)) + '|']
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out) + '\n'


def hours(x):
    return f'{x / 3600:.2f}'


def write_report(path, sing, speech, log, args):
    langs = list(dict.fromkeys(it['language'] for it in sing))
    L = []
    L.append('# GTSinger data report\n')
    L.append(f'Generated by `preprocess/gtsinger_split_report.py` from `{args.meta_dir}`. '
             f'Held-out singers: {", ".join(args.unseen_singers)}. Seed {args.seed}, '
             f'at least {args.min_minutes:g} min of singing per singer in `valid` and in `test_seen`.\n')

    L.append('## Splits\n')
    rows = []
    for sp in SPLITS:
        a = [it for it in sing if it['split'] == sp]
        b = [it for it in speech if it['split'] == sp]
        rows.append([sp, len(a), hours(sum(it['duration'] for it in a)), len({it['singer'] for it in a}),
                     len({song_key(it) for it in a}), len(b), hours(sum(it['duration'] for it in b))])
    rows.append(['total', len(sing), hours(sum(it['duration'] for it in sing)), len({it['singer'] for it in sing}),
                 len({song_key(it) for it in sing}), len(speech), hours(sum(it['duration'] for it in speech))])
    L.append(table(['split', 'singing clips', 'singing h', 'singers', 'songs', 'speech clips', 'speech h'], rows))

    L.append('## Singing hours by language and split\n')
    rows = []
    for lang in langs:
        a = [it for it in sing if it['language'] == lang]
        rows.append([lang] + [hours(sum(it['duration'] for it in a if it['split'] == sp)) for sp in SPLITS]
                    + [hours(sum(it['duration'] for it in a)), len(a)])
    L.append(table(['language'] + SPLITS + ['total h', 'clips'], rows))

    L.append('## Singers\n')
    rows = []
    for singer in dict.fromkeys(it['singer'] for it in sing):
        a = [it for it in sing if it['singer'] == singer]
        rows.append([singer, a[0]['gender'], a[0]['vocal_range'], len(a), len({song_key(it) for it in a})]
                    + [hours(sum(it['duration'] for it in a if it['split'] == sp)) for sp in SPLITS])
    L.append(table(['singer', 'gender', 'range', 'clips', 'songs'] + [sp + ' h' for sp in SPLITS], rows))

    L.append('## Groups and style labels (singing clips)\n')
    grp = collections.Counter('control' if 'Control' in it['item_name'].split('#')[4] else 'technique' for it in sing)
    L.append(f"Control-group clips: {grp['control']}; technique-group clips: {grp['technique']}.\n")
    for g in ('emotion', 'singing_method', 'pace', 'range'):
        c = collections.Counter(it[g] for it in sing)
        L.append(f"- `{g}`: " + ', '.join(f'{k} {v}' for k, v in c.most_common()))
    L.append('')
    sung = collections.Counter()
    tech_time = collections.defaultdict(collections.Counter)
    for it in sing:
        for i, (p, d) in enumerate(zip(it['ph'], it['ph_durs'])):
            if p in REST:
                continue
            sung[it['language']] += d
            for t in TECHS:
                if it[t + '_tech'][i]:
                    tech_time[it['language']][t] += d
    L.append('Share of sung time carrying each technique flag (%):\n')
    L.append(table(['language'] + TECHS, [[lang] + [f'{100 * tech_time[lang][t] / sung[lang]:.1f}' for t in TECHS] for lang in langs]))

    L.append('## Phonemes and clip length\n')
    rows = []
    for lang in langs:
        a = [it for it in sing if it['language'] == lang]
        b = [it for it in speech if it['language'] == lang]
        inv = {p for it in a + b for p in it['ph'] if p not in REST}
        long = [it for it in a if it['duration'] > 20]
        zero = sum(d for it in a for p, d, x in zip(it['ph'], it['ph_durs'], it['ep_pitches']) if p not in REST and x == 0)
        rows.append([lang, len(inv), f"{sum(len(it['ph']) for it in a) / len(a):.0f}", sum(len(it['ph']) > 100 for it in a),
                     len(long), hours(sum(it['duration'] - 20 for it in long)), f'{100 * zero / sung[lang]:.1f}'])
    L.append(table(['language', 'phonemes', 'mean pieces/clip', 'clips >100 pieces', 'clips >20 s', 'hours beyond 20 s',
                    '% sung time without note pitch'], rows))
    L.append('"Pieces" are phonemes after splitting at note boundaries. Clips longer than 20 s are kept; '
             'feature extraction should truncate rather than drop them. Sung phonemes without a note pitch come from '
             'audio-transcribed notes (Japanese, Korean) that mark sung passages as rests.\n')

    L.append('## Cleaning\n')
    L.append(f"Built {log['built']['singing']} singing and {log['built']['speech']} speech clips; "
             f"kept {len(sing)} and {len(speech)}. Dropped for rare phonemes: {len(log['dropped_rare_phoneme'])} clips "
             f"({len(log['rare_phonemes'])} symbols). Emotion labels fixed: {log['emotion_fixed'] or 'none'}.\n")
    keys = sorted({k for v in log['steps'].values() for k in v})
    rows = [[name] + [v.get(k, 0) for k in keys] for name, v in log['steps'].items() if v]
    L.append(table(['subset'] + [k.replace('_', ' ') for k in keys], rows))
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--meta_dir', default='data/meta')
    parser.add_argument('--unseen_singers', nargs='*', default=['IT-Bass-2', 'KO-Soprano-1'])
    parser.add_argument('--min_minutes', type=float, default=5.0)
    parser.add_argument('--seed', type=int, default=1234)
    args = parser.parse_args()

    load = lambda name: json.load(open(os.path.join(args.meta_dir, name), encoding='utf-8'))
    sing, speech, log = load('metadata.json'), load('metadata_speech.json'), load('cleaning_log.json')
    missing = set(args.unseen_singers) - {it['singer'] for it in sing}
    assert not missing, f'unknown singers: {missing}'

    song_split = assign_splits(sing, set(args.unseen_singers), args.min_minutes * 60, args.seed)
    for it in sing + speech:
        it['split'] = 'test_unseen' if it['singer'] in args.unseen_singers else song_split.get(song_key(it), 'train')

    # no song and no held-out singer may straddle train and an evaluation split
    by_split = collections.defaultdict(set)
    for it in sing + speech:
        by_split[it['split']].add(song_key(it))
    assert not by_split['train'] & (by_split['valid'] | by_split['test_seen'] | by_split['test_unseen'])
    assert not by_split['valid'] & (by_split['test_seen'] | by_split['test_unseen'])
    assert all((it['singer'] in args.unseen_singers) == (it['split'] == 'test_unseen') for it in sing + speech)

    for name, items in (('metadata.json', sing), ('metadata_speech.json', speech)):
        with open(os.path.join(args.meta_dir, name), 'w', encoding='utf-8') as f:
            json.dump(items, f, ensure_ascii=False)
    os.makedirs(os.path.join(args.meta_dir, 'splits'), exist_ok=True)
    for sp in SPLITS:
        with open(os.path.join(args.meta_dir, 'splits', sp + '.txt'), 'w', encoding='utf-8') as f:
            f.write(''.join(it['item_name'] + '\n' for it in sing if it['split'] == sp))
    write_report(os.path.join(args.meta_dir, 'report.md'), sing, speech, log, args)
    for sp in SPLITS:
        a = [it for it in sing if it['split'] == sp]
        print(f"{sp:12s} {len(a):6d} clips {sum(it['duration'] for it in a) / 3600:6.2f} h")
