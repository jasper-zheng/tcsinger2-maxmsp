"""The data of the JS front-end in Max (export/max/js, D1 of EXPORTING_WORK_PACKAGES.md).

Writes CommonJS modules (`module.exports = JSON.parse("...")`) into export/max/js/lib/data/, so that the JS
g2p gives what ldm/infer/g2p.py gives without porting what can be precomputed:

  tcs_data_phones.js        phone set (id order), pads, nucleus flag per phoneme (timing.is_nucleus),
                            phonemes per language, language_set, LANG_SUFFIX, PH_FIXES, IPA_LANGS, ...
  tcs_data_lexicon.js       data/meta/lexicon.json
  tcs_data_dict_<lang>.js   the MFA dictionary: word -> its most probable variant inside the phone set (with
                            the language suffix left out), and for French, Italian and Spanish the dictionary
                            word of each spelling without accents (g2p._unaccented)
  tcs_data_pinyin.js        Chinese, from pypinyin itself (INITIALS and FINALS, strict, as g2p._chinese):
                            phrases: every phrase of its phrase dictionary -> phonemes per character;
                            chars: every character of U+4E00-9FFF and U+3400-4DBF -> phonemes
                            (null where g2p._zh_syllable refuses its reading); and pypinyin's
                            initials and finals, for pinyin typed as text (ported in tcs_pinyin.js).

Each file records the hash of data/meta/phone_set.json, which the JS checks. The files are generated, not
committed (about 53 MB). Usage (from TCSinger2/):  python scripts/build_max_js_data.py [--out export/max/js/lib/data]
"""
import argparse
import hashlib
import json
import os
import sys
import time

sys.path.insert(0, os.getcwd())  # so that it also runs without PYTHONPATH=.

from ldm.data.phone_set import (MIDI_PAD_ID, NOTE_TYPE_PAD, PH_PAD_ID, PHONE_SET_PATH, language_set,  # noqa: E402
                                ph_set)
from ldm.infer import g2p  # noqa: E402
from ldm.infer.timing import is_nucleus  # noqa: E402

FORMAT = 'tcsinger2-js-data/1'


def phone_set_hash():
    with open(PHONE_SET_PATH, 'rb') as f:
        return hashlib.sha1(f.read()).hexdigest()


def write_module(path, data):
    """module.exports = JSON.parse("..."): JSON.parse keeps keys like __proto__ as own properties."""
    text = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    with open(path, 'w', encoding='utf-8') as f:
        f.write(f'// generated by scripts/build_max_js_data.py; do not edit\nmodule.exports = JSON.parse({json.dumps(text, ensure_ascii=False)});\n')
    return os.path.getsize(path)


def phones():
    by_lang = {lang: [p[:-len(s)] for p in ph_set if p.endswith(s)] for lang, s in g2p.LANG_SUFFIX.items()}
    return dict(ph_set=ph_set, nucleus=[p not in g2p.REST and is_nucleus(p) for p in ph_set], PH_PAD_ID=PH_PAD_ID,
                MIDI_PAD_ID=MIDI_PAD_ID, NOTE_TYPE_PAD=NOTE_TYPE_PAD, language_set=language_set, LANG_SUFFIX=g2p.LANG_SUFFIX,
                PH_FIXES=g2p.PH_FIXES, IPA_LANGS=sorted(g2p.IPA_LANGS), WEAK_DICT=list(g2p.WEAK_DICT),
                ACCENT_LANGS=list(g2p.ACCENT_LANGS), ZH_FINAL_FIXES=g2p.ZH_FINAL_FIXES, phonemes=by_lang)


def mfa(language):
    suffix = len(g2p.LANG_SUFFIX[language])
    words = {w: ' '.join(p[:-suffix] for p in max(v, key=lambda x: x[0])[1]) for w, v in g2p.mfa_dict(language).items()}
    out = dict(words=words)
    if language in g2p.ACCENT_LANGS:
        out['unaccented'] = g2p._unaccented(language)
    return out


def _han(lo, hi):
    return [chr(c) for c in range(lo, hi + 1)]


def pinyin():
    import pypinyin
    from pypinyin import Style, lazy_pinyin
    from pypinyin.constants import PHRASES_DICT
    from pypinyin.style._constants import _FINALS, _INITIALS, _INITIALS_NOT_STRICT

    def convert(text):
        a = lazy_pinyin(text, style=Style.INITIALS, strict=True)
        b = lazy_pinyin(text, style=Style.FINALS, strict=True)
        assert len(a) == len(b) == len(text), text
        return [g2p._zh_syllable(x, y) for x, y in zip(a, b)]

    chars = {c: convert(c)[0] for c in _han(0x4E00, 0x9FFF) + _han(0x3400, 0x4DBF)}
    phrases = {p: convert(p) for p in PHRASES_DICT}
    return dict(pypinyin=pypinyin.__version__, chars=chars, phrases=phrases, initials=_INITIALS,
                initials_not_strict=_INITIALS_NOT_STRICT, finals=_FINALS)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--out', default='export/max/js/lib/data')
    args = p.parse_args()
    os.makedirs(args.out, exist_ok=True)
    head = dict(format=FORMAT, phone_set_sha1=phone_set_hash())
    jobs = [('phones', phones), ('lexicon', lambda: dict(lexicon={lang: g2p.lexicon(lang) for lang in language_set})),
            ('pinyin', pinyin)]
    jobs += [(f'dict_{lang.lower()}', (lambda lang=lang: mfa(lang))) for lang in language_set if lang != 'Chinese']
    total = 0
    for name, make in jobs:
        t = time.time()
        size = write_module(os.path.join(args.out, f'tcs_data_{name}.js'), {**head, **make()})
        total += size
        print(f'tcs_data_{name}.js  {size / 1e6:6.2f} MB  ({time.time() - t:.1f} s)')
    print(f'total {total / 1e6:.1f} MB in {args.out}')


if __name__ == '__main__':
    main()
